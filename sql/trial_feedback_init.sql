CREATE TABLE IF NOT EXISTS `trial_feedback` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '反馈ID',
  `submission_code` VARCHAR(40) NOT NULL COMMENT '匿名回执编号',
  `user_id` BIGINT NOT NULL COMMENT '已登录用户ID，仅用于真实性核验',
  `participant_type` VARCHAR(16) NOT NULL COMMENT 'STUDENT/TEACHER',
  `institution` VARCHAR(120) DEFAULT NULL COMMENT '学校或单位（选填）',
  `job_role` VARCHAR(64) NOT NULL COMMENT '体验的目标岗位',
  `course_id` VARCHAR(64) DEFAULT NULL COMMENT '体验课程标识',
  `stage_id` INT DEFAULT NULL COMMENT '体验阶段',
  `flow_completed` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否完成主流程',
  `path_score` TINYINT NOT NULL COMMENT '路径清晰度1-5',
  `resource_score` TINYINT NOT NULL COMMENT '资源岗位匹配度1-5',
  `course_score` TINYINT NOT NULL COMMENT '课程任务对应度1-5',
  `tutor_score` TINYINT NOT NULL COMMENT '导师可执行性1-5',
  `trust_score` TINYINT NOT NULL COMMENT '来源、AI标识和安全提示清晰度1-5',
  `most_helpful` VARCHAR(1000) NOT NULL COMMENT '最有帮助的部分',
  `improvement` VARCHAR(1000) NOT NULL COMMENT '最需要改进的问题',
  `continue_use` TINYINT(1) NOT NULL COMMENT '是否愿意继续使用',
  `authenticity_confirmed` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '本人确认真实体验',
  `anonymous_use_consent` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '同意匿名用于比赛材料',
  `submitted_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '提交时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_trial_feedback_submission_code` (`submission_code`),
  KEY `idx_trial_feedback_user_time` (`user_id`, `submitted_at`),
  KEY `idx_trial_feedback_role` (`job_role`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='真实用户试用反馈';
