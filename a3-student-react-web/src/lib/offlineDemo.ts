export const OFFLINE_DEMO_ENABLED = import.meta.env.VITE_ENABLE_OFFLINE_DEMO !== "false";
export const OFFLINE_DEMO_MESSAGE = "后端未连接，当前展示离线演示内容。";

export async function resolveWithOfflineDemo<T>(
  loader: () => Promise<T>,
  fallback: () => T,
  message = OFFLINE_DEMO_MESSAGE,
): Promise<{ data: T; isOfflineDemo: boolean; error: string | null }> {
  try {
    const data = await loader();
    return { data, isOfflineDemo: false, error: null };
  } catch (error) {
    if (!OFFLINE_DEMO_ENABLED) {
      throw error;
    }
    return {
      data: fallback(),
      isOfflineDemo: true,
      error: message,
    };
  }
}

